module.exports.run = async function ({ api, event, args, Economy }) {
  const { threadID, messageID, senderID } = event;
  const bet = 200;
  const reward = 440;

  // فحص الرصيد من نظام الـ Economy الجديد
  let userMoney = await Economy.getBalance(senderID, "money");
  if (userMoney < bet) {
    return api.sendMessage(`رصيدك غير كافٍ للمراهنة. تحتاج ${bet}$ ؛-؛`, threadID, messageID);
  }

  // اختيار شخصية عشوائية وتلميح عشوائي لها
  const character = animeCharacters[Math.floor(Math.random() * animeCharacters.length)];
  const hint = character.hints[Math.floor(Math.random() * character.hints.length)];

  // خصم مبلغ المراهنة عبر نظام Economy الخاص بك
  await Economy.decrease(bet, senderID, "money");

  const msg = `●─────── ✾ ───────●\n ⦿ ⟬ 👤 𝐀𝐍Ｉ𝐌𝐄 𝐐𝐔𝐈𝐙 ⟭ ⦿\n⊱ ────────────── ⊰\n ⟣ 📜 الوصف: "${hint}"\n ⟣ ⏳ الوقت: 60 ثانية\n ⟣ 💰 المراهنة: ${bet}$\n ⟣ 🏆 الجائزة: ${reward}$\n⊱ ────────────── ⊰\nخمن اسم الشخصية ؛-؛\n●─────── ✾ ───────●`;

  return api.sendMessage(msg, threadID, (err, info) => {
    if (err) return;

    global.client.handleReply.push({
      name: "تخمين",
      messageID: info.messageID,
      author: senderID,
      answer: character.name,
      reward: reward,
      createdAt: Date.now()
    });

    // مؤقت انتهاء الـ 60 ثانية
    setTimeout(() => {
      const index = global.client.handleReply.findIndex(item => item.messageID === info.messageID);
      if (index !== -1) {
        global.client.handleReply.splice(index, 1);
        api.sendMessage(`⏳ انتهى الوقت! الشخصية كانت: ${character.name} ؛-؛`, threadID);
      }
    }, 60000);
  }, messageID);
};

module.exports.handleReply = async function ({ api, event, handleReply, Economy }) {
  const { threadID, messageID, senderID, body } = event;
  if (senderID !== handleReply.author) return;

  const userAnswer = body.trim().toLowerCase();
  const correctAnswer = handleReply.answer.toLowerCase();

  if (userAnswer === correctAnswer) {
    // إضافة جائزة الفوز عبر نظام Economy الجديد
    await Economy.increase(handleReply.reward, senderID, "money");
    api.sendMessage(`✅ أحسنت! الإجابة صحيحة. حصلت على ${handleReply.reward}$ ؛-؛`, threadID, messageID);

    // إزالة العملية من كاش الردود كي لا يتداخل مع التايم أوت
    const index = global.client.handleReply.findIndex(item => item.messageID === handleReply.messageID);
    if (index !== -1) global.client.handleReply.splice(index, 1);
  } else {
    api.sendMessage("❌ خطأ، حاول مرة أخرى أو انتظر انتهاء الوقت ؛-؛", threadID, messageID);
  }
};
