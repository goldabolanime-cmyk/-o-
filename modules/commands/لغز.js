module.exports.run = async function({ api, event, Economy }) {
  const { threadID, messageID } = event;

  // اختيار لغز عشوائي من قاعدة البيانات الكبيرة
  const randomRiddle = riddlesDatabase[Math.floor(Math.random() * riddlesDatabase.length)];

  const rewardMoney = 80; // قيمة الجائزة الثابتة كما طلبت

  const challengeMsg = `🧩 ❯──「 تـحـدي 」──❮ 🧩\n\n` +
                        `❓ اللغز: ${randomRiddle.question}\n\n` +
                        `⏳ الوقت: دقيقة واحدة فقط.\n` +
                        `💰 الجائزة: ${rewardMoney}$\n\n` +
                        `✍ رد بالإجابة سريعاً!\n` +
                        `🧩 ❯───────────❮ 🧩`;

  api.sendMessage(challengeMsg, threadID, (err, info) => {
    if (err || !info) return;

    // دفع معطيات اللغز بداخل مصفوفة الـ handleReply للتحقق اللاحق
    global.client.handleReply.push({
      name: module.exports.config.name,
      messageID: info.messageID,
      correctAnswers: randomRiddle.answers,
      reward: rewardMoney,
      isEnded: false,
      createdAt: Date.now()
    });

    // وضع مؤقت (تايمر) مدته دقيقة واحدة (60000 مللي ثانية) لإنهاء اللغز وحذف الرسالة
    setTimeout(async () => {
      const index = global.client.handleReply.findIndex(r => r.messageID === info.messageID);
      if (index !== -1 && !global.client.handleReply[index].isEnded) {
        global.client.handleReply[index].isEnded = true;
        try { await api.unsendMessage(info.messageID); } catch (e) {}
        api.sendMessage("⏳ | انتهت الدقيقة ولم ينجح أحد في حل اللغز في الوقت المحدد!", threadID);
      }
    }, 60000);
  }, messageID);
};

// ══════════════════════════════════════════
// HANDLE REPLY (التحقق الفوري من الإجابة الصادرة)
// ══════════════════════════════════════════
module.exports.handleReply = async function({ api, event, handleReply, Economy }) {
  const { threadID, messageID, senderID, body } = event;

  // التحقق مما إذا كان اللغز قد انتهى وقته أو تم حله مسبقاً
  if (handleReply.isEnded) return;

  // تنظيف النص المدخل من قبل المستخدم لزيادة دقة الفحص تلقائياً
  const cleanInput = body.trim().toLowerCase()
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ال/g, ""); // إزالة ال التعريف للفحص المرن

  // فحص الإجابة ومقارنتها بقائمة الإجابات الصحيحة المتاحة للغز
  const isCorrect = handleReply.correctAnswers.some(ans => {
    const cleanAns = ans.trim().toLowerCase()
      .replace(/[أإآ]/g, "ا")
      .replace(/ة/g, "ه")
      .replace(/ال/g, "");
    return cleanInput === cleanAns;
  });

  if (isCorrect) {
    handleReply.isEnded = true; // إنهاء الجلسة فوراً لمنع التكرار

    // إضافة الجائزة المالية للمستخدم الفائز عبر نظام الإيكونومي بداخل البوت
    await Economy.increase(handleReply.reward, senderID, "money");

    // حذف رسالة اللغز فوراً من الشات بناءً على نجاح الحل والتنظيف
    try { await api.unsendMessage(handleReply.messageID); } catch (e) {}

    const winMsg = `🎉 | تهانينا! إجابتك صحيحة وهي: (${body})\n💰 | لقد ربحت الجائزة الكبرى بقيمة: ${handleReply.reward}$`;
    return api.sendMessage(winMsg, threadID, messageID);
  } else {
    // إشعار المستخدم بأن الإجابة خاطئة مع ترك الفرصة قائمة للآخرين حتى انتهاء الدقيقة
    return api.sendMessage("❌ | إجابة خاطئة! حاول مجدداً قبل انتهاء الوقت.", threadID, messageID);
  }
};
