const BOX = (title, lines, footer = null) => {
  let m = `●─────── ✾ ───────●\n ⦿ ⟬ ${title} ⟭ ⦿\n⊱ ────────────── ⊰\n`;
  for (const l of lines) { 
    if (!l && l !== 0) { m += `\n`; } 
    else { m += `  ⟣ ${l}\n`; } 
  }
  if (footer) { 
    m += `⊱ ────────────── ⊰\n`; 
    for (const f of footer) { 
      if (!f && f !== 0) { m += `\n`; } 
      else { m += `  ⟣ ${f}\n`; } 
    } 
  }
  return m + '●─────── ✾ ───────●';
};

