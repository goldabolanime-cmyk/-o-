// لضمان عدم تكرار الإرسال في نفس الدقيقة
let lastSentTime = "";

// ══════════════════════════════════════════
// HANDLE EVENT (نظام الفحص والجدولة التلقائي المتوافق مع الأندكس)
// ══════════════════════════════════════════
module.exports.handleEvent = async function({ api }) {
  const now = new Date();
  // جلب الوقت الحالي بتوقيت المغرب (24 ساعة)
  const moroccoTime = now.toLocaleTimeString("en-US", { timeZone: "Africa/Casablanca", hour12: false });
  const [currentHour, currentMinute] = moroccoTime.split(":");
  const currentTimeStr = `${currentHour}:${currentMinute}`;

  // إذا تم الإرسال في هذه الدقيقة مسبقاً، تخطى الفحص فوراً لمنع التكرار والضغط
  if (currentTimeStr === lastSentTime) return;

  // البحث عن تطابق توقيت الذكر المجدول الحين
  const targetZikr = scheduledAzkar.find(z => z.time === currentTimeStr);

  if (targetZikr) {
    lastSentTime = currentTimeStr; // حفظ دقيقة الإرسال فوراً لمنع السبام والكرش الحلقي
    console.log(`[AUTO-AZKAR] 📢 حان الآن موعد: ${targetZikr.title}. جاري الإرسال للمجموعات...`);

    // جلب غرف الدردشة مباشرة وبأمان تام من ملف قاعدة بيانات النواة المتواجد بـ index.js
    const THREADS_PATH = path.join(process.cwd(), "database", "threads.json");
    let threadsData = {};

    try {
      if (fs.existsSync(THREADS_PATH)) {
        threadsData = JSON.parse(fs.readFileSync(THREADS_PATH, "utf8") || "{}");
      }
    } catch (err) {
      console.error("[AUTO-AZKAR ERROR] فشل قراءة ملف المجموعات:", err.message);
      return;
    }

    const groupIDs = Object.keys(threadsData);

    if (groupIDs.length === 0) return;

    // صياغة الرسالة بالزخرفة الملكية الفخمة للبوت
    const msgText = BOX(targetZikr.title, [targetZikr.text]);

    // الإرسال لكافة الجروبات المسجلة في السورس بشكل متتابع ومحمي
    groupIDs.forEach(tid => {
      api.sendMessage(msgText, tid, (sendErr) => {
        if (sendErr) console.error(`[AUTO-AZKAR ERROR] تعذر الإرسال للمجموعة ذات المعرف: ${tid}`);
      });
    });
  }
};

// ══════════════════════════════════════════
// RUN (العمل اليدوي عند كتابة كلمة اذكار)
// ══════════════════════════════════════════
module.exports.run = async function({ api, event }) {
  const { threadID, messageID } = event;

  try {
    // اختيار ذكر عشوائي من الـ 20 ذكراً
    const randomZikr = azkarList[Math.floor(Math.random() * azkarList.length)];

    // بناء الرسالة اليدوية بالزخرفة الملكية
    const finalMsg = BOX("📿 ذِكْرٌ عَشْوَائِيٌّ", [randomZikr], ["أَلاَ بِذِكْرِ اللَّهِ تَطْمَئِنُّ الْقُلُوبُ"]);

    return api.sendMessage(finalMsg, threadID, messageID);

  } catch (e) {
    console.error("[AZKAR COMMAND ERROR]", e);
    return api.sendMessage(BOX("❌ خَطَأٌ", ["حدث خطأ أثناء جلب الذكر اليدوي."]), threadID, messageID);
  }
};
