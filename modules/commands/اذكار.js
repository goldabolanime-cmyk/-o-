// لضمان عدم إرسال نفس الذكر أكثر من مرة خلال نفس الدقيقة
let lastSentTime = "";

// ══════════════════════════════════════════
// ONLOAD (نظام الجدولة التلقائي عند تشغيل البوت)
// ══════════════════════════════════════════
module.exports.onLoad = async function({ api }) {
  console.log("[AUTO-AZKAR] ⏱️ تم تشغيل نظام جدولة الأذكار التلقائي بنجاح...");

  // فحص الوقت كل 30 ثانية لدقة متناهية وعدم فوات التوقيت
  setInterval(async () => {
    // جلب الوقت الحالي بتوقيت المغرب الدقيق (24 ساعة)
    const now = new Date();
    const moroccoTime = now.toLocaleTimeString("en-US", { timeZone: "Africa/Casablanca", hour12: false });
    const [currentHour, currentMinute] = moroccoTime.split(":");
    const currentTimeStr = `${currentHour}:${currentMinute}`;

    // إذا تم الإرسال في هذه الدقيقة مسبقاً، تخطى الفحص
    if (currentTimeStr === lastSentTime) return;

    // البحث في الأذكار المجدولة عن تطابق الوقت الحالي
    const targetZikr = scheduledAzkar.find(z => z.time === currentTimeStr);

    if (targetZikr) {
      lastSentTime = currentTimeStr; // تسجيل الدقيقة لمنع التكرار
      console.log(`[AUTO-AZKAR] 📢 حان الآن موعد: ${targetZikr.title}. جاري الإرسال للمجموعات...`);

      // جلب المجموعات بشكل ديناميكي وآمن لحل مشكلة الكاش الفارغ
      api.getThreadList(100, null, ["INBOX"], (err, list) => {
        if (err) return console.error("[AUTO-AZKAR ERROR] فشل جلب قائمة المجموعات:", err);

        // تصفية القائمة للتأكد من أنها مجموعات نشطة (Group Threads)
        const allGroups = list.filter(t => t.isGroup && t.isSubscribed);

        allGroups.forEach(group => {
          let msg = `╭──⟪ ${targetZikr.title} ⟫──╮\n\n` +
                    `${targetZikr.text}\n\n` +
                    `╰────────────────╯`;

          api.sendMessage(msg, group.threadID, (sendErr) => {
            if (sendErr) console.error(`[AUTO-AZKAR ERROR] فشل الإرسال للمجموعة ${group.threadID}`);
          });
        });
      });
    }
  }, 30000); // الفحص كل 30 ثانية يضمن التقاط الدقيقة بالضبط دون استهلاك موارد السيرفر
};

// ══════════════════════════════════════════
// RUN (العمل اليدوي عند كتابة كلمة اذكار)
// ══════════════════════════════════════════
module.exports.run = async function({ api, event }) {
  const { threadID, messageID } = event;

  try {
    // اختيار ذكر عشوائي من الـ 20 ذكراً
    const randomZikr = azkarList[Math.floor(Math.random() * azkarList.length)];

    // بناء الرسالة بالزخرفة المطلوبة
    const finalMsg = `${header}\n\n` +
                     `${randomZikr}\n\n` +
                     `${footer}`;

    return api.sendMessage(finalMsg, threadID, messageID);

  } catch (e) {
    console.error("[AZKAR COMMAND ERROR]", e);
    return api.sendMessage("❌ حدث خطأ أثناء جلب الذكر.", threadID, messageID);
  }
};
